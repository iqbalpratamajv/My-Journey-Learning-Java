package com.iqbal.branching.function;

public class MenghitungOrang {
    public static void main(String[] args) {
        int orangDalamRuangan = 0;

        orangDalamRuangan++;
        orangDalamRuangan++;
        orangDalamRuangan++;

        System.out.println("orang didalam ruangan: "+orangDalamRuangan);

        orangDalamRuangan--;

        System.out.println("Orang dalam ruangan: "+orangDalamRuangan);
    }
}
