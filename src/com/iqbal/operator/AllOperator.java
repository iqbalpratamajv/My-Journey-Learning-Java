package com.iqbal.operator;

public class AllOperator {
    public static void main(String[] args) {
        int numberOne = 10;
        int numberTwo = 5;

        System.out.println("Operasi Aritmatika");
        System.out.println("Penjumlahan: " + (numberOne + numberTwo));
        System.out.println("Pengurangan: " + (numberOne - numberTwo));
        System.out.println("Perkalian: " + (numberOne * numberTwo));
        System.out.println("Pembagian: " + (numberOne / numberTwo));
        System.out.println("Modulus: " + (numberOne % numberTwo));
    }
}
