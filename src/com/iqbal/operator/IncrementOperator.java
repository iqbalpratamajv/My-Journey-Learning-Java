package com.iqbal.operator;

public class IncrementOperator {
    public static void main(String[] args) {
        int numberA = 1;
        System.out.println("numberA = " + numberA);
        System.out.println("++numberA = " + ++numberA);

        System.out.println();
        int numberB = 1;
        System.out.println("NumberB = " + numberB);
        System.out.println("NumberB++ = " + ++numberB);

        System.out.println();
        int numberC = 1;
        System.out.println("NumberC = " + numberC);
        System.out.println("NumberC-- = " + --numberC);
    }
}
