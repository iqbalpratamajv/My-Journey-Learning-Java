package com.iqbal.repetition;

public class Table8Sub2 {
    public static void main(String[] args) {
        for (int a = 1; a <= 20; a++) {
            System.out.println("Tambah");
        }
        System.out.println();

        for (int a = 20; a >= 1; a--) {
            System.out.println("Kurang");
        }
    }
}
