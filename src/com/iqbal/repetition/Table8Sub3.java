package com.iqbal.repetition;

public class Table8Sub3 {
    public static void main(String[] args) {
        for (int a = 1; a <= 20; a += 2) {
            System.out.print(a + " ");
        }

        System.out.println();

        for (int a = 20; a >= 1; a -= 2) {
            System.out.print(a + " ");
        }
    }

}
